"""
Analyze worst-outlier samples from the trained Teacher (T, C) -> phi predictions.

Prints per-chunk top-k worst cases and compares:
  - Teacher prediction vs True Reference error for phi
  - Input T/C statistics of the worst cases

Also plots the single worst outlier per specified chunk.

Usage:
    python analyze_teacher_outliers.py --chunk_id 6 --top_k 10
"""
import argparse
import numpy as np
import matplotlib.pyplot as plt


L = 2.0
H = 1.0


def relative_l2(pred, true, axis=None):
    if axis is None:
        return np.linalg.norm(pred - true) / (np.linalg.norm(true) + 1e-12)
    return np.linalg.norm(pred - true, axis=axis) / (np.linalg.norm(true, axis=axis) + 1e-12)


def phi_statistics(phi_i):
    return {
        'min': phi_i.min(),
        'max': phi_i.max(),
        'mean': phi_i.mean(),
        'std': phi_i.std(),
        'range': phi_i.max() - phi_i.min(),
        'peak_to_mean': phi_i.max() / (phi_i.mean() + 1e-12),
    }


def input_statistics(T_i, C_i):
    return {
        'T_min': T_i.min(),
        'T_max': T_i.max(),
        'T_range': T_i.max() - T_i.min(),
        'C_min': C_i.min(),
        'C_max': C_i.max(),
        'C_range': C_i.max() - C_i.min(),
    }


def print_chunk_outlier_table(T_chunk, C_chunk, phi_pred_chunk, phi_true_chunk,
                              chunk_id, start_idx, top_k=10):
    N = phi_pred_chunk.shape[0]
    rel_l2 = relative_l2(
        phi_pred_chunk.reshape(N, -1),
        phi_true_chunk.reshape(N, -1),
        axis=1
    )

    worst_idx = np.argsort(rel_l2)[-top_k:][::-1]

    print("\n" + "=" * 130)
    print(f"Chunk {chunk_id}: top {top_k} worst Teacher-vs-True cases "
          f"(global indices [{start_idx}, {start_idx + N}))")
    print("=" * 130)
    print(f"{'global_idx':>12} {'rel_l2_%':>12} "
          f"{'phi_min':>14} {'phi_max':>14} {'phi_mean':>14} {'phi_std':>14} {'peak/mean':>12} "
          f"{'T_min':>10} {'T_max':>10} {'T_range':>12} {'C_min':>12} {'C_max':>12} {'C_range':>14}")

    for idx in worst_idx:
        global_idx = start_idx + idx
        pstats = phi_statistics(phi_true_chunk[idx])
        istats = input_statistics(T_chunk[idx], C_chunk[idx])
        print(f"{global_idx:12d} {rel_l2[idx]*100:11.4f}% "
              f"{pstats['min']:14.4e} {pstats['max']:14.4e} {pstats['mean']:14.4e} "
              f"{pstats['std']:14.4e} {pstats['peak_to_mean']:12.2f} "
              f"{istats['T_min']:10.2f} {istats['T_max']:10.2f} {istats['T_range']:12.2f} "
              f"{istats['C_min']:12.4e} {istats['C_max']:12.4e} {istats['C_range']:14.4e}")

    return worst_idx, rel_l2


def plot_worst(X, Y, T_i, C_i, phi_pred, phi_true, global_idx, save_path):
    rel_l2 = relative_l2(phi_pred, phi_true)

    fig, axes = plt.subplots(2, 3, figsize=(15, 9))

    ax = axes[0, 0]
    c = ax.contourf(X, Y, T_i, levels=20, cmap='viridis')
    ax.set_title(f"Instance {global_idx}: T")
    ax.set_xlabel("x [m]")
    ax.set_ylabel("y [m]")
    plt.colorbar(c, ax=ax)

    ax = axes[0, 1]
    c = ax.contourf(X, Y, C_i, levels=20, cmap='plasma')
    ax.set_title(f"Instance {global_idx}: C")
    ax.set_xlabel("x [m]")
    ax.set_ylabel("y [m]")
    plt.colorbar(c, ax=ax)

    vmin = min(phi_pred.min(), phi_true.min())
    vmax = max(phi_pred.max(), phi_true.max())

    ax = axes[0, 2]
    c = ax.contourf(X, Y, phi_pred, levels=20, cmap='hot', vmin=vmin, vmax=vmax)
    ax.set_title("Teacher Prediction")
    ax.set_xlabel("x [m]")
    ax.set_ylabel("y [m]")
    plt.colorbar(c, ax=ax)

    ax = axes[1, 0]
    c = ax.contourf(X, Y, phi_true, levels=20, cmap='hot', vmin=vmin, vmax=vmax)
    ax.set_title("True Reference")
    ax.set_xlabel("x [m]")
    ax.set_ylabel("y [m]")
    plt.colorbar(c, ax=ax)

    ax = axes[1, 1]
    err = np.abs(phi_pred - phi_true)
    c = ax.contourf(X, Y, err, levels=20, cmap='coolwarm')
    ax.set_title(f"|Teacher - True| (RelL2={rel_l2*100:.3f}%)")
    ax.set_xlabel("x [m]")
    ax.set_ylabel("y [m]")
    plt.colorbar(c, ax=ax)

    ax = axes[1, 2]
    mid_j = phi_true.shape[0] // 2
    ax.plot(X[mid_j, :], phi_true[mid_j, :], 'b-', label='True', linewidth=2)
    ax.plot(X[mid_j, :], phi_pred[mid_j, :], 'r--', label='Teacher', linewidth=2)
    ax.set_title(f"Midline y={Y[mid_j, 0]:.2f} m")
    ax.set_xlabel("x [m]")
    ax.set_ylabel("phi")
    ax.legend()

    plt.tight_layout()
    plt.savefig(save_path, dpi=150, bbox_inches='tight')
    plt.close()
    print(f"Saved figure to {save_path}")


def main():
    parser = argparse.ArgumentParser(description='Analyze Teacher worst outliers for (T, C) -> phi.')
    parser.add_argument('--T_file', type=str, default='1_FFT_T_10000_101_201.npy')
    parser.add_argument('--C_file', type=str, default='1_FFT_C_10000_101_201.npy')
    parser.add_argument('--phi_pred_file', type=str, default='phi_pred_10000_201_101.npy')
    parser.add_argument('--phi_true_file', type=str, default='phi_true_10000_201_101.npy')
    parser.add_argument('--chunk_id', type=int, default=None,
                        help='Chunk to analyze (0-9). If None, analyze all chunks.')
    parser.add_argument('--instances_per_chunk', type=int, default=1000)
    parser.add_argument('--top_k', type=int, default=10)
    args = parser.parse_args()

    T = np.load(args.T_file)                     # (N, ny, nx)
    C = np.load(args.C_file)                     # (N, ny, nx)
    phi_pred = np.load(args.phi_pred_file)       # (N, nx, ny) or (N, ny, nx)
    phi_true = np.load(args.phi_true_file)       # (N, nx, ny) or (N, ny, nx)

    # Ensure phi arrays match T/C spatial shape (ny, nx)
    if phi_pred.shape[1:] != T.shape[1:]:
        phi_pred = phi_pred.transpose(0, 2, 1)
    if phi_true.shape[1:] != T.shape[1:]:
        phi_true = phi_true.transpose(0, 2, 1)

    assert T.shape == C.shape == phi_pred.shape == phi_true.shape, \
        f"T {T.shape}, C {C.shape}, phi_pred {phi_pred.shape}, phi_true {phi_true.shape} must match"

    N = T.shape[0]
    n_chunks = (N + args.instances_per_chunk - 1) // args.instances_per_chunk

    ny, nx = T.shape[1], T.shape[2]
    x = np.linspace(0.0, L, nx)
    y = np.linspace(0.0, H, ny)
    X, Y = np.meshgrid(x, y)

    chunks_to_analyze = [args.chunk_id] if args.chunk_id is not None else list(range(n_chunks))

    for chunk_id in chunks_to_analyze:
        start = chunk_id * args.instances_per_chunk
        end = min(start + args.instances_per_chunk, N)

        T_chunk = T[start:end]
        C_chunk = C[start:end]
        phi_pred_chunk = phi_pred[start:end]
        phi_true_chunk = phi_true[start:end]

        worst_idx, rel_l2 = print_chunk_outlier_table(
            T_chunk, C_chunk, phi_pred_chunk, phi_true_chunk,
            chunk_id, start, top_k=args.top_k
        )

        # Plot the single worst case for this chunk
        worst_local = worst_idx[0]
        global_idx = start + worst_local
        save_path = f"teacher_T_C_2_phi_outlier_chunk_{chunk_id}_inst_{global_idx}.png"
        plot_worst(X, Y,
                   T_chunk[worst_local], C_chunk[worst_local],
                   phi_pred_chunk[worst_local], phi_true_chunk[worst_local],
                   global_idx, save_path)

